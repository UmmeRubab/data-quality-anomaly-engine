'use client';

import { useEffect, useState } from 'react';

type Metrics = { accuracy: number; precision_macro: number; recall_macro: number; f1_macro: number; n_samples: number };
type Experiment = { noise_rate: number; seed: number; clean: Metrics; corrupted: Metrics; accuracy_change: number; f1_macro_change: number };
type Preview = { filename: string; columns: string[]; rows: Record<string, string>[] };
const API = process.env.NEXT_PUBLIC_API_URL || 'http://127.0.0.1:8000';

export default function Home() {
  const [status, setStatus] = useState('Checking API…');
  const [noise, setNoise] = useState(0.2);
  const [seed, setSeed] = useState(42);
  const [running, setRunning] = useState(false);
  const [result, setResult] = useState<Experiment | null>(null);
  const [files, setFiles] = useState<string[]>([]);
  const [selected, setSelected] = useState('');
  const [preview, setPreview] = useState<Preview | null>(null);
  const [error, setError] = useState('');

  useEffect(() => {
    fetch(`${API}/api/health`).then(r => { if (!r.ok) throw Error('API unavailable'); return r.json(); })
      .then(() => setStatus('Connected')).catch(() => setStatus('Offline — start FastAPI'));
    fetch(`${API}/api/results/files`).then(r => r.json()).then(d => setFiles(d.files || [])).catch(() => {});
  }, []);

  async function run() {
    setRunning(true); setError('');
    try {
      const response = await fetch(`${API}/api/experiments/label-noise`, {
        method: 'POST', headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ noise_rate: noise, seed }),
      });
      const body = await response.json();
      if (!response.ok) throw Error(body.detail || 'Experiment failed');
      setResult(body);
    } catch (e) { setError(e instanceof Error ? e.message : 'Unknown error'); }
    finally { setRunning(false); }
  }

  async function openPreview(filename: string) {
    setSelected(filename); setError('');
    try {
      const response = await fetch(`${API}/api/results/preview?filename=${encodeURIComponent(filename)}&limit=20`);
      const body = await response.json();
      if (!response.ok) throw Error(body.detail || 'Preview failed');
      setPreview(body);
    } catch (e) { setError(e instanceof Error ? e.message : 'Preview failed'); }
  }

  const fmt = (n: number) => (n * 100).toFixed(2) + '%';
  return <main>
    <header><p className="eyebrow">DATA-CENTRIC AI RESEARCH</p><h1>DataGuard AI</h1><p>Reproducible data quality and machine learning robustness experiments</p><span className="status">API: {status}</span></header>
    <section className="panel"><h2>Label-noise experiment</h2><p>Train two identical classifiers on clean versus corrupted labels, and evaluate both on the same untouched test set.</p>
      <div className="controls"><label>Noise rate <strong>{Math.round(noise * 100)}%</strong><input aria-label="Noise rate" type="range" min="0" max="0.5" step="0.05" value={noise} onChange={e => setNoise(Number(e.target.value))}/></label>
      <label>Random seed <input aria-label="Random seed" type="number" min="0" max="4294967295" value={seed} onChange={e => setSeed(Number(e.target.value))}/></label>
      <button onClick={run} disabled={running}>{running ? 'Running…' : 'Run experiment'}</button></div>
      {error && <p role="alert" className="error">{error}</p>}
      {result && <div className="metrics"><article><span>Clean accuracy</span><strong>{fmt(result.clean.accuracy)}</strong></article><article><span>Corrupted accuracy</span><strong>{fmt(result.corrupted.accuracy)}</strong></article><article><span>Accuracy change</span><strong>{fmt(result.accuracy_change)}</strong></article><article><span>Macro F1 change</span><strong>{fmt(result.f1_macro_change)}</strong></article></div>}
    </section>
    <section className="panel"><h2>Saved benchmark results</h2><p>CSV files generated by the Phase 1 experiment suite.</p>
      {files.length === 0 ? <p>No CSV results found yet. Run the Phase 1 benchmark first.</p> : <div className="filelist">{files.map(file => <button className={selected === file ? 'active' : ''} key={file} onClick={() => openPreview(file)}>{file}</button>)}</div>}
      {preview && <div className="tablewrap"><h3>{preview.filename} — first {preview.rows.length} rows</h3><table><thead><tr>{preview.columns.map(c => <th key={c}>{c}</th>)}</tr></thead><tbody>{preview.rows.map((row, i) => <tr key={i}>{preview.columns.map(c => <td key={c}>{row[c]}</td>)}</tr>)}</tbody></table></div>}
    </section><footer>DataGuard AI · Experimental research dashboard · Synthetic-data baseline</footer>
  </main>;
}
